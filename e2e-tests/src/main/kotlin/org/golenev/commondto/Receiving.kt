package org.golenev.commondto
import com.fasterxml.jackson.databind.JsonNode

/** Диагностическое состояние приёмки. Некорректные исходные данные сохраняются как JSON, без приведения к DTO корректной поставки. */
data class Receiving(
    /**
     * Идентификатор магазина, к которому относятся данные.
     */
    val storeId: String,
    /**
     * Бизнес-идентификатор поставки; сохраняется при её повторной отправке.
     */
    val deliveryId: String,
    /**
     * Неизменяемый порядковый номер первой приёмки поставки в магазине; определяет порядок обновления цены остатка.
     */
    val deliverySequence: Long,
    /**
     * Состояние приёмки: ожидание расчёта цены, оприходование или отклонение.
     */
    val state: DeliveryState,
    /**
     * Время первой приёмки поставки сервисом WAREHOUSE.
     */
    val receivedAt: String,
    /**
     * Количество начатых попыток расчёта цены поставки.
     */
    val attemptCount: Long,
    /**
     * Сохранённые позиции поставки; сведения о тарифе и продажной цене появляются после расчёта.
     */
    val items: List<PricedLine>,
    /**
     * Время успешного оприходования поставки; null, пока она не оприходована.
     */
    val postedAt: String? = null,
    /**
     * Время следующей запланированной попытки расчёта цены; null, если повтор не запланирован.
     */
    val nextAttemptAt: String? = null,
    /**
     * Последняя ошибка приёмки или расчёта цены; null, если ошибка отсутствует.
     */
    val lastError: PricingFailure? = null,
    /**
     * Исходные данные отклонённой поставки как JSON; null для поставки, которая не отклонена.
     */
    val rejectedPayload: JsonNode? = null
)
