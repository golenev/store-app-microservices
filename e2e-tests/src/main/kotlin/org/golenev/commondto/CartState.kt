package org.golenev.commondto

/** Допустимые состояния корзины v1. Неизвестное состояние сервера считается ошибкой разбора, а не пустой корзиной. */
enum class CartState {
    /**
     * Корзина открыта: её позиции можно изменять и оформлять.
     */
    OPEN,
    /**
     * Корзина оформлена: состав принятой заявки уже зафиксирован.
     */
    SUBMITTED
}
